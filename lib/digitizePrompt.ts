export function getDigitizeVisionPrompt(eraseHandwriting: boolean = true): string {
  if (eraseHandwriting) {
    return `你是一位资深教师与试卷电子化数字化专家。请仔细查看这张试卷/讲义/作业照片，将其完整、高精度地重构成标准的 Markdown 格式电子版试卷，彻底消除所有拍照阴影与瑕疵。

【核心重点 - 移除手写笔记，还原纯净空白试卷】：
1. 试卷中可能包含学生手写的笔迹（铅笔、钢笔、圆珠笔）、学生作答填写的文字/数字/算式，以及老师批改打勾打叉的红笔印记。
2. 请务必【彻底忽略并擦除所有手写笔记与红笔批改标记】，千万不要把学生手写作答内容录入到试卷中！
3. 将所有作答横线、填空处统一还原为纯净的标准空白下划线 "________"（8~12个连续下划线），解答题/作文题留出空白作答横线区，还原为一张未经作答的全新空白原始试卷。

【识别与格式重构规范】：
1. 试卷标题：使用一级大标题，如 "# 8A U2 默写讲义"
2. 试卷副标题/信息栏：包含姓名、日期、班级、得分等，如 "**Name: ____________  Date: ____________  Score: ______**"
3. 大题标题：使用二级标题，如 "## 一、根据音标和句意写出单词。"
4. 小题与填空：
   - 严格保留题号（如 "1.", "2." 等）。
   - 填空横线统一使用标准下划线 "________"（8~12个连续下划线）呈现。
   - 英语音标请务必准确保留国际音标符号（如 /haɪt/, /'haɪɪst/, /'ɪtəli/, /ɪ'tæliən/, /'spænɪʃ/ 等）。
   - 句子翻译/整句填空题目，请在答题处留出充足横线：如 "________ we have ________, I can ________________________."
5. 数学/理科公式与几何符号规范：
   - 几何角统一使用标准几何角符号 "∠"（如 ∠A, ∠BFC, ∠AEB, ∠1, ∠2）或标准 LaTeX "$\angle A$"。
   - 三角形使用 "△"（如 △ABC, △PBF）。
   - 度数使用标准度数符号 "°"（如 90°, 60°, 45°）或 "$90^\circ$"。
   - 分数与复杂代数算式：严格使用标准 LaTeX 格式包裹（如 "$\frac{1}{2}\angle A$" 或 "$\angle BFC = 90^\circ + \frac{1}{2}\angle A$"），务必两端配对单美元符 "$" 包裹，不要添加多余反斜杠转义。
6. 去除任何杂物：忽略照片边缘的桌子、阴影、手指、纸张折痕或杂污。

【输出要求】：
直接输出完整的 Markdown 文本，不要在开头或结尾添加多余的解释客套话。
`;
  } else {
    return `你是一位资深教师与试卷电子化数字化专家。请仔细查看这张试卷/讲义/作业照片，将其完整、高精度地重构成标准的 Markdown 格式电子版试卷。

【模式 - 保留学生手写作答与笔记】：
1. 请完整识别试卷原本的题目排版结构。
2. 同时将学生在试卷上手写填写的答案、作答记录保留在对应的填空或作答位置（若有红笔批改符号可忽略，保留学生原答案）。
3. 试卷大标题使用一级大标题，大题使用二级大标题，公式使用标准 LaTeX 格式包裹（如 $x^2 + y^2 = r^2$）。

【输出要求】：
直接输出完整的 Markdown 文本，不要在开头或结尾添加多余的解释客套话。
`;
  }
}

export const DIGITIZE_VISION_PROMPT = getDigitizeVisionPrompt(true);

